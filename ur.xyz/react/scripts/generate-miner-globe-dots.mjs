#!/usr/bin/env node
// Generates src/data/minerGlobeDots.js, the land dot field behind the Miners
// page's globe intro (components/MinerGlobeIntro.jsx): one dot per grid cell
// of land, with the SDK palette color of the country it sits in.
//
// Inputs live in the ur.io checkout beside this repo (~/urnetwork is a
// monoroot of sibling repos): Natural Earth 110m as topojson, d3-geo and
// topojson-client from its node_modules, and the country palette
// (react/src/data/countries.js, the same table the SDK's GetColorHex uses).
// A country outside that table takes the SDK's fallback: the average of two
// palette colors picked by hashing its id.
//
//   node scripts/generate-miner-globe-dots.mjs [step degrees, default 3]
//
// The grid is area-uniform: rows every STEP degrees of latitude, and each
// row holds as many dots as fit STEP degrees of arc at that latitude, with
// every other row offset half a cell.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const urio = path.resolve(here, "../../../../mmm/ur.io/react");
if (!fs.existsSync(path.join(urio, "src/components/ip/world-110m.json"))) {
  console.error(`generate-miner-globe-dots: needs the ur.io checkout at ${urio}`);
  process.exit(1);
}
const require = createRequire(path.join(urio, "package.json"));
const { geoContains } = await import(require.resolve("d3-geo"));
const topojson = await import(require.resolve("topojson-client"));
const { COUNTRIES } = await import(path.join(urio, "src/data/countries.js"));

const STEP = Number(process.argv[2] || 3);
const world = JSON.parse(fs.readFileSync(path.join(urio, "src/components/ip/world-110m.json"), "utf8"));
const land = topojson.feature(world, world.objects.land);
const countries = topojson.feature(world, world.objects.countries).features;

const colorByNumeric = {};
for (const c of COUNTRIES) colorByNumeric[c.isoNumeric] = c.color.toLowerCase();
const known = [...new Set(Object.values(colorByNumeric))].sort();

function hashIndex(s, n) {
  let h = 2166136261;
  for (const ch of s) { h ^= ch.charCodeAt(0); h = Math.imul(h, 16777619) >>> 0; }
  return h % n;
}
function mix(a, b) {
  const ca = a.slice(1).match(/../g).map((x) => parseInt(x, 16));
  const cb = b.slice(1).match(/../g).map((x) => parseInt(x, 16));
  return "#" + ca.map((v, i) => Math.round((v + cb[i]) / 2).toString(16).padStart(2, "0")).join("");
}
function countryColor(id) {
  if (colorByNumeric[id]) return colorByNumeric[id];
  return mix(known[hashIndex(id, known.length)], known[hashIndex(id + "salt", known.length)]);
}

const palette = [];
const paletteIndex = {};
const dots = [];
let rows = 0;
for (let lat = -84; lat <= 84 + 1e-9; lat += STEP) {
  rows += 1;
  const nLon = Math.max(1, Math.round((360 * Math.cos((lat * Math.PI) / 180)) / STEP));
  const offset = rows % 2 ? 0 : 0.5;
  for (let i = 0; i < nLon; i += 1) {
    const lon = -180 + ((i + 0.5 + offset) * 360) / nLon;
    const pt = [lon, lat];
    if (!geoContains(land, pt)) continue;
    const country = countries.find((f) => geoContains(f, pt));
    const color = country ? countryColor(country.id) : "#5c6b7a";
    if (paletteIndex[color] === undefined) { paletteIndex[color] = palette.length; palette.push(color); }
    dots.push([Number(lon.toFixed(2)), Number(lat.toFixed(2)), paletteIndex[color]]);
  }
}

const out = path.join(here, "../src/data/minerGlobeDots.js");
fs.writeFileSync(out,
  "// Generated by scripts/generate-miner-globe-dots.mjs. DO NOT EDIT.\n" +
  "// Land dots for the Miners globe intro: [lon, lat, palette index] per dot,\n" +
  `// ${STEP}° area-uniform grid over Natural Earth 110m land, colored by the SDK's\n` +
  "// country palette.\n" +
  `export const MINER_GLOBE_STEP = ${STEP};\n` +
  `export const MINER_GLOBE_PALETTE = ${JSON.stringify(palette)};\n` +
  `export const MINER_GLOBE_DOTS = ${JSON.stringify(dots)};\n`);
console.log(`wrote ${path.relative(process.cwd(), out)}: ${dots.length} dots, ${palette.length} colors, step ${STEP}°`);
